"""Collect amendments from NosDéputés.fr for legislature 13 (2007-2012).

NosDéputés.fr (Regards Citoyens) provides a JSON API with all amendments
filed during legislature 13. This is the only source for AN amendments
before the AN open data portal (which starts at legislature 14).

Legislature 12 (2002-2007) is NOT available on this source.

Usage (library only, no __main__):
    from src.collectors.nosdeputes import collect_nosdeputes_amendments
    collect_nosdeputes_amendments(Path("data/raw"))
"""

import json
import logging
import time
from pathlib import Path

import httpx

logger = logging.getLogger(__name__)

NOSDEPUTES_BASE = "https://2007-2012.nosdeputes.fr"
USER_AGENT = "IntentionLegislateur/1.0 (legal research; +https://github.com/plouis01/legal-project)"

# Finance law text numbers for legislature 13 (AN text reference numbers).
# Each entry: (text_number, label, law_type)
# Numbers verified against the NosDéputés.fr API.
# Some texts return 500 (server-side issue) — the collector retries and skips gracefully.
FINANCE_LAW_TEXTS = [
    # PLF (Projets de Loi de Finances)
    (189, "PLF 2008", "LF"),
    (1127, "PLF 2009", "LF"),
    (1946, "PLF 2010", "LF"),
    (2824, "PLF 2011", "LF"),
    (3775, "PLF 2012", "LF"),
    # PLFSS (Projets de Loi de Financement de la Sécurité Sociale)
    (284, "PLFSS 2008", "LFSS"),
    (1183, "PLFSS 2009", "LFSS"),
    (1976, "PLFSS 2010", "LFSS"),
    (2848, "PLFSS 2011", "LFSS"),
    (3790, "PLFSS 2012", "LFSS"),
    # PLFR (Projets de Loi de Finances Rectificative)
    (947, "PLFR 2008", "LFR"),
    (1494, "PLFR 2009 (1)", "LFR"),
    (2070, "PLFR 2009 (2)", "LFR"),
    (2944, "PLFR 2010", "LFR"),
    (3406, "PLFR 2011 (1)", "LFR"),
    (3713, "PLFR 2011 (2)", "LFR"),
]

# Path to CGI mapping file generated by scripts/build_nosdeputes_mapping.py
CGI_MAPPING_FILE = Path(__file__).parent.parent.parent / "data" / "nosdeputes_leg13_cgi_texts.json"


def _load_text_list() -> list[tuple[int, str, str]]:
    """Load text list from CGI mapping file, falling back to hardcoded finance texts.

    The mapping file is generated by ``scripts/build_nosdeputes_mapping.py``
    and contains both the hardcoded finance law texts AND fuzzy-matched CGI texts.

    Returns:
        List of (text_number, label, law_type) tuples.
    """
    if CGI_MAPPING_FILE.exists():
        try:
            with open(CGI_MAPPING_FILE, "r", encoding="utf-8") as f:
                entries = json.load(f)
            texts = []
            seen = set()
            for entry in entries:
                tn = entry["text_number"]
                if tn in seen:
                    continue
                seen.add(tn)
                texts.append((tn, entry.get("label", f"Text {tn}"), entry.get("law_type", "LOI")))
            logger.info(f"Loaded {len(texts)} texts from CGI mapping file ({CGI_MAPPING_FILE.name})")
            return texts
        except (json.JSONDecodeError, KeyError) as e:
            logger.warning(f"Failed to load CGI mapping file: {e}, falling back to hardcoded texts")

    logger.info(f"Using hardcoded finance law texts ({len(FINANCE_LAW_TEXTS)} texts)")
    return FINANCE_LAW_TEXTS

# Delays
REQUEST_DELAY = 1.0  # seconds between requests
BACKOFF_DELAY = 30.0  # seconds on 429/503
MAX_RETRIES = 3


def collect_nosdeputes_amendments(output_dir: Path) -> None:
    """Collect all CGI law amendments from NosDéputés.fr for legislature 13.

    Uses the CGI mapping file if available (generated by
    ``scripts/build_nosdeputes_mapping.py``), otherwise falls back to the
    hardcoded FINANCE_LAW_TEXTS list.

    Args:
        output_dir: Base raw data directory (e.g., data/raw).
                    Files are saved to {output_dir}/nosdeputes/leg13/
    """
    leg_dir = output_dir / "nosdeputes" / "leg13"
    leg_dir.mkdir(parents=True, exist_ok=True)

    text_list = _load_text_list()

    headers = {
        "User-Agent": USER_AGENT,
        "Accept": "application/json",
    }

    total_amendments = 0
    total_texts = 0
    skipped = 0

    with httpx.Client(timeout=30.0, headers=headers, follow_redirects=True) as client:
        for text_number, label, law_type in text_list:
            output_file = leg_dir / f"text_{text_number}.json"

            # Skip if already downloaded
            if output_file.exists():
                try:
                    with open(output_file, "r", encoding="utf-8") as f:
                        existing = json.load(f)
                    count = len(existing.get("amendements", []))
                    logger.info(f"  [{label}] Already exists ({count} amendements), skipping")
                    total_amendments += count
                    total_texts += 1
                    skipped += 1
                    continue
                except (json.JSONDecodeError, KeyError):
                    pass  # Re-download if file is corrupted

            url = f"{NOSDEPUTES_BASE}/amendements/{text_number}/json"
            logger.info(f"  [{label}] Fetching text {text_number} ...")

            data = _fetch_with_retry(client, url, label)
            if data is None:
                continue

            # Save raw response with metadata
            data["_metadata"] = {
                "text_number": text_number,
                "label": label,
                "law_type": law_type,
                "source": "nosdeputes.fr",
                "legislature": 13,
            }

            with open(output_file, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)

            count = len(data.get("amendements", []))
            total_amendments += count
            total_texts += 1
            logger.info(f"  [{label}] Saved {count} amendements -> {output_file.name}")

            time.sleep(REQUEST_DELAY)

    logger.info(
        f"NosDéputés collection complete: {total_amendments} amendements "
        f"across {total_texts} texts ({skipped} skipped)"
    )


def _fetch_with_retry(
    client: httpx.Client, url: str, label: str
) -> dict | None:
    """Fetch JSON from NosDéputés.fr with retry on transient errors.

    The API sometimes returns PHP warnings before the JSON payload,
    so we strip everything before the first '{'.

    Args:
        client: httpx client instance
        url: URL to fetch
        label: Human-readable label for logging

    Returns:
        Parsed JSON dict, or None on failure
    """
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = client.get(url)
            response.raise_for_status()
            text = response.text

            # Strip PHP warnings/notices that may precede the JSON
            brace_idx = text.find("{")
            if brace_idx > 0:
                stripped = text[:brace_idx].strip()
                if stripped:
                    logger.debug(f"  [{label}] Stripped {len(stripped)} chars of PHP output")
                text = text[brace_idx:]

            if not text.strip():
                logger.warning(f"  [{label}] Empty response")
                return None

            return json.loads(text)

        except httpx.HTTPStatusError as e:
            status = e.response.status_code
            if status in (429, 503) and attempt < MAX_RETRIES:
                wait = BACKOFF_DELAY * attempt
                logger.warning(
                    f"  [{label}] {status} on attempt {attempt}/{MAX_RETRIES}, "
                    f"waiting {wait:.0f}s..."
                )
                time.sleep(wait)
            elif status == 500:
                # Server-side error — log and skip (some texts consistently 500)
                logger.warning(
                    f"  [{label}] Server error 500 (attempt {attempt}/{MAX_RETRIES})"
                )
                if attempt < MAX_RETRIES:
                    time.sleep(BACKOFF_DELAY)
                else:
                    logger.warning(f"  [{label}] Giving up after {MAX_RETRIES} attempts")
                    return None
            else:
                logger.error(f"  [{label}] HTTP {status}: {e}")
                return None

        except (json.JSONDecodeError, httpx.RequestError) as e:
            logger.warning(f"  [{label}] Error on attempt {attempt}/{MAX_RETRIES}: {e}")
            if attempt < MAX_RETRIES:
                time.sleep(BACKOFF_DELAY)
            else:
                return None

    return None
